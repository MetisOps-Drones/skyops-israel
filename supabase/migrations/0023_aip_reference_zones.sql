-- Advisory "AIP reference" layer for the map, built from the official CAAI
-- low-level transit route charts (מפת נתיבי תובלה נמוכה CVFR — North sheet
-- ed. 1/23, South sheet ed. 2/25). This is DELIBERATELY separate from
-- `airspace_zones`: these rows are digitized by eye against the printed
-- lat/lon graticule and known airfield coordinates, not surveyed — the
-- center/radius are approximate circles standing in for the real (often
-- irregular) boundaries. They must never feed `find_intersecting_zones` or
-- any other automated clearance check; the client renders them as a
-- clearly-labeled, toggleable reference overlay only (see
-- AirspaceHUD/LayerControlPanel), same spirit as the DronesIL outbound link.

create type aip_zone_kind as enum ('CTR', 'ATZ', 'TMA', 'CTA', 'RESTRICTED', 'DANGER', 'PROHIBITED');

create table aip_reference_zones (
  id uuid primary key default uuid_generate_v4(),
  name text not null,
  code text,
  kind aip_zone_kind not null,
  altitude_text text not null,
  min_altitude_ft integer,
  max_altitude_ft integer,
  center_lng double precision not null,
  center_lat double precision not null,
  radius_m integer not null,
  source_sheet text not null,
  source_edition text not null,
  created_at timestamptz not null default timezone('utc', now())
);

alter table aip_reference_zones enable row level security;

create policy "Authenticated users read AIP reference zones"
  on aip_reference_zones for select
  to authenticated
  using (true);

