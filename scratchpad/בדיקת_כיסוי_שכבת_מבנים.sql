-- שאילתת בדיקה בלבד (SELECT, לא משנה שום דבר) — מטרתה לבדוק אם שכבת
-- המבנים (buildings) מכילה בכלל נתונים אמיתיים באזור מרכז ראשון לציון
-- (הנקודה מהצילום מסך: 31°58'37"N 34°47'49"E), או שהיא ריקה/חלקית שם.

-- 1. כמה שורות יש בכלל בטבלה (המצופה: מיליוני שורות אם הטעינה בוצעה במלואה
--    על כל ישראל):
select count(*) as total_buildings from buildings;

-- 2. כמה מבנים יש ברדיוס 500 מטר מהנקודה המדויקת מהצילום מסך (מרכז
--    ראשון לציון). אם התוצאה היא 0, זה סימן חד-משמעי שאין כיסוי אמיתי
--    באזור הזה בטבלה — לא באג בקוד, אלא פער בטעינת הנתונים:
select count(*) as nearby_buildings
from buildings
where st_dwithin(
  geography(geom),
  geography(st_setsrid(st_makepoint(34.796944, 31.976944), 4326)),
  500
);
